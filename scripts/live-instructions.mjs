// node scripts/live-instructions.mjs [--check] [--tester <agent name>] [crew]
// Writes docs/live-agent-instructions.md from templates/jam-room.template.yaml (crew defaults to "jam"):
// one copy-paste block per agent, for agents created by hand in Switch Console (the Windows path).
// --tester: the playtester's agent name when it differs from <crew>-playtester, e.g. jam-playtester-gpt
//           for a hand-made Codex playtester; every handoff to it is renamed.
// --check: exit 1 if the doc is out of date with the template (used by the clean-clone test); it reuses
//          the crew and tester recorded in the doc unless given.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const check = args.includes('--check');
const file = path.join(ROOT, 'docs', 'live-agent-instructions.md');
const recorded = (fs.existsSync(file) && check && fs.readFileSync(file, 'utf8').match(/with crew = ([^,\s]+), playtester = ([^\s]+?)\.\s*$/m)) || [];
const ti = args.indexOf('--tester');
const positional = args.filter((a, i) => !a.startsWith('--') && i !== ti + 1);
const crew = positional[0] || recorded[1] || 'jam';
const tester = (ti >= 0 && args[ti + 1]) || recorded[2] || `${crew}-playtester`;
const sub = t => t.replaceAll('{crew}-playtester', tester).replaceAll('{crew}', crew);
const yaml = fs.readFileSync(path.join(ROOT, 'templates', 'jam-room.template.yaml'), 'utf8').replace(/\r\n/g, '\n');

// Tiny reader for this template's shape: "  - name:" agent items with addressing + "instructions: |".
const agents = [];
const lines = yaml.split('\n');
for (let i = 0; i < lines.length; i++) {
  const name = lines[i].match(/^  - name: "?([^"]+)"?$/);
  if (name) { agents.push({ name: sub(name[1]), addressing: '', provider: '', text: [] }); continue; }
  const a = agents[agents.length - 1];
  if (!a) continue;
  const addr = lines[i].match(/^    addressing: (\S+)/);
  if (addr) a.addressing = addr[1];
  const prov = lines[i].match(/^    provider: "?([^"\s]+)"?/);
  if (prov) a.provider = prov[1] === '{tester_provider}' ? 'codex (Claude Code as fallback)' : prov[1];
  if (/^    instructions: \|$/.test(lines[i])) {
    for (i++; i < lines.length && (lines[i] === '' || lines[i].startsWith('      ')); i++) a.text.push(sub(lines[i].slice(6)));
    i--;
  }
  if (/^\S/.test(lines[i])) break; // left the agents: list
}
if (agents.length !== 3 || agents.some(a => !a.text.length)) { console.error('Could not read 3 agents with instructions.'); process.exit(1); }

const out = [
  '# Live agent instructions (paste into Switch Console)', '',
  `Generated by scripts/live-instructions.mjs from templates/jam-room.template.yaml with crew = ${crew}, playtester = ${tester}.`,
  'Keep the two identical: edit the template, re-run the script, paste each block into',
  'Console > Your Agents > agent > Settings > Instructions, set Addressing as shown, save,',
  'then type `!reset-all-agents` in each room (a resumed session keeps old memory).', '',
  ...agents.flatMap(a => [`## ${a.name}`, '', `Addressing: **${a.addressing}** · Provider: **${a.provider}**`, '', '```text', ...a.text.join('\n').trimEnd().split('\n'), '```', '']),
].join('\n');

if (check) {
  const same = fs.existsSync(file) && fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') === out;
  console.log(same ? 'LIVE INSTRUCTIONS MATCH TEMPLATE' : 'LIVE INSTRUCTIONS OUT OF DATE: run node scripts/live-instructions.mjs');
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(file, out);
console.log(`Wrote docs/live-agent-instructions.md (${agents.map(a => a.name).join(', ')})`);
